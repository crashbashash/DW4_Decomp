#!/usr/bin/env python3
"""Extract logo model-sequence commands from AREA 620; no action durations inferred."""
import argparse
import hashlib
import json
import struct
import sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT.parent/'scripts'))
from modelctrl_dump import Pack, load_igb, afs_entry

def generate(afs):
    ii,ids=load_igb(str(ROOT.parent / 'scripts'))
    blob=afs_entry(afs,620)
    pk=Pack(ii,ids,blob,str(ROOT.parent / 'data/reflection.json'))
    info=[i for i in range(pk.cnt) if pk.cls(i)=='beModelCtrlInfo' and pk.rname(i)=='j_startlogo']
    assert len(info)==1
    groups=[i for i in pk.list_ids(pk.fields(info[0])['slot5']) if pk.cls(i)=='beModelCtrlInfoDataSeq']
    assert len(groups)==1
    seqs=pk.list_ids(pk.fields(groups[0])['_dataList'])
    result=['/* Generated by tools/gen_logo_program.py from AREA 620 j_startlogo.',f' * Pack SHA256: {hashlib.sha256(blob).hexdigest()} */']
    commands=[];rows=[]
    for seq in seqs:
        start=len(commands)
        for cmd in pk.list_ids(pk.fields(seq)['_comList']):
            op=pk.cls(cmd).removeprefix('beModelCtrl')
            assert op in ('ACTION','WCHECK','JUMP'),op
            name=pk.rname(cmd)
            assert name in ('OPEN','CLOSE','Action','SQ_WAIT','SQ_ERAS'),name
            commands.append(f'    {{ LOGO_{op}, LOGO_{name} }}, /* asset id {cmd} */')
        rows.append(f'    {{ LOGO_{pk.rname(seq)}, {start}, {len(commands)-start} }}, /* asset id {seq} */')
    result+=['static const struct logo_command logo_commands[] = {',*commands,'};','static const struct logo_sequence logo_sequences[] = {',*rows,'};','']
    model_text='\n'.join(result)
    ai=[i for i in range(pk.cnt) if pk.cls(i)=='beAction2Info' and pk.rname(i)=='j_startlogo']
    assert len(ai)==1
    components=[];actions=[]
    bits=lambda f:struct.unpack('<I',struct.pack('<f',f))[0]
    for action in pk.list_ids(pk.fields(ai[0])['_dataList']):
        name=pk.rname(action)
        if name not in ('OPEN','CLOSE'):continue
        start=len(components)
        for cmd in pk.list_ids(pk.fields(action)['_comList']):
            kind=pk.cls(cmd).removeprefix('beAction2');f=pk.fields(cmd)
            assert kind in ('FADESET','JOINTSET','WAITCHECK'),kind
            f1=f.get('_startTime',f.get('_waitTime',f.get('_fadeTime',0)))
            f2=f.get('_endTime',f.get('_fadeValue',0))
            text=json.dumps(pk.rname(cmd));loop=json.dumps(f.get('_loopMode','').rstrip('\0'))
            components.append(f'    {{ A2H_{kind}, {text}, 0x{bits(f1):08x}u, 0x{bits(f2):08x}u, {loop} }}, /* asset id {cmd} */')
        actions.append(f'    {{ LOGO_{name}, {start}, {len(components)-start} }}, /* asset id {action} */')
    action_text='\n'.join([result[0],result[1],
        'static const struct logo_a2_component logo_a2_components[] = {',*components,'};',
        'static const struct logo_a2_action logo_a2_actions[] = {',*actions,'};',''])
    return {'logo_program.h':model_text,'logo_action2_program.h':action_text}
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--afs',type=Path,default=ROOT.parent.parent / 'local/extracted/AREA.AFS');p.add_argument('--check',action='store_true');a=p.parse_args()
    for name,text in generate(a.afs).items():
        out=ROOT/'src'/name
        if a.check:assert out.read_text()==text, name+' differs from asset; regenerate'
        else:out.write_text(text)
    print('logo program: asset commands verified' if a.check else 'logo program: generated')

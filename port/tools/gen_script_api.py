#!/usr/bin/env python3
"""Generate be method names from the recovered retail descriptor table."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--check', action='store_true')
a = p.parse_args()
rows = json.loads((ROOT.parent / 'data/script_api.json').read_text())
names = dict.fromkeys(r['name'] for r in rows)
s = '/* Generated by tools/gen_script_api.py; retail descriptor names. */\n'
s += ''.join('    ' + json.dumps(x) + ',\n' for x in names)
out = ROOT / 'src/script_api_names.h'
if a.check:
    assert out.read_text() == s, 'script API names differ; regenerate'
else:
    out.write_text(s)
print(f'Lua API: {len(rows)} descriptors, {len(names)} method names')

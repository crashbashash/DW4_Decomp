#!/usr/bin/env python3
"""Regenerate the factual Unicode/game-byte pairs used by retail 382eb0."""
import argparse
from pathlib import Path
import struct

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--elf',type=Path,default=Path(__file__).resolve().parents[2].parent/'local/extracted/SLUS_208.36')
p.add_argument('--out',type=Path,default=Path(__file__).resolve().parents[1]/'src/textcodec_table.inc')
p.add_argument('--check',action='store_true')
a=p.parse_args()
if not a.elf.exists():
    if a.check:print('text codec table: private ELF unavailable, skipped');raise SystemExit(0)
    p.error('private retail ELF unavailable')
data=a.elf.read_bytes();pairs=[]
for i in range(425):
    unicode,encoded=struct.unpack_from('<HH',data,0x4c8880-0x100000+0x80+i*4)
    if unicode==0xffff:break
    pairs.append((unicode,encoded))
assert len(pairs)==424 and (0x2286,0x81ba) in pairs and (0x8d6b,0x8a71) in pairs
text='/* Generated by tools/gen_textcodec_table.py: retail 4c8880 Unicode/game-byte pairs. */\n'
text+=''.join('    {0x%04x,0x%04x},\n'%v for v in pairs)
if a.check:assert a.out.read_text()==text,'regenerate textcodec_table.inc'
else:a.out.write_text(text)
print(f'text codec: {len(pairs)} original mapping pairs '+('verified' if a.check else 'generated'))

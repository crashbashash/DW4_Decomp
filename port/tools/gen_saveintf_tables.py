#!/usr/bin/env python3
"""Generate src/saveintf_tables.inc: the static tables of the retail shared data-select interface
(beNDMWSaveIntf, 4081a0 / helpers 3d9de0..3f13d0) decoded from the USA ELF.

Usage: gen_saveintf_tables.py <SLUS_208.36> > src/saveintf_tables.inc

Tables (retail addresses): message table 4cda40 (360 rows of {id, TXT call, text-slot list}), area windows 4cc830,
slot-line sequences 4cc840/4cc850, memory-card slot rows 4cd060/4cd090, panel positions 4cf640, digimon model table 4cec70,
the Create starters 4cd0d0/4cd0e0 and the name-entry key rows 4cc860."""
import struct, sys

d = open(sys.argv[1], 'rb').read()
ph = struct.unpack_from('<I', d, 0x1c)[0]
n = struct.unpack_from('<H', d, 0x2c)[0]
segs = [struct.unpack_from('<8I', d, ph + 32 * i) for i in range(n)]


def rd(a, l=4):
    for t, off, va, pa, fs, ms, fl, al in segs:
        if va <= a < va + fs:
            return d[off + a - va:off + a - va + l]
    raise KeyError(hex(a))


def u32(a): return struct.unpack('<I', rd(a))[0]
def s32(a): return struct.unpack('<i', rd(a))[0]
def f32(a): return struct.unpack('<f', rd(a))[0]


def cstr(a):
    out = b''
    while True:
        c = rd(a + len(out), 1)
        if c == b'\0':
            return out.decode('ascii')
        out += c


def fl(v):
    t = '%.9g' % v
    return (t if ('.' in t or 'e' in t) else t + '.0') + 'f'


def q(s): return '"' + s + '"'


o = []
o.append('/* Generated by tools/gen_saveintf_tables.py from the retail ELF; do not edit. */')
# message table
rows = []
a = 0x4cda40
while u32(a) != 0xffffffff:
    idv, call, lst = u32(a), s32(a + 4), u32(a + 8)
    ents = []
    p = lst
    while u32(p) != 0:
        ents.append((cstr(u32(p)), u32(p + 4), u32(p + 8)))
        p += 12
    rows.append((idv, call, ents))
    a += 12
lists = []
for r in rows:
    if r[2] not in lists:
        lists.append(r[2])
o.append('typedef struct {const char *group;uint8_t kind,index;} dw4_si_slot;')
for i, l in enumerate(lists):
    o.append('static const dw4_si_slot si_slots_%d[]={%s};' % (i, ','.join('{%s,%d,%d}' % (q(g), k, x) for g, k, x in l)))
o.append('static const struct {uint32_t id;int32_t call;const dw4_si_slot *slots;unsigned count;} si_messages[]={')
for idv, call, ents in rows:
    i = lists.index(ents)
    o.append('    {0x%x,%d,si_slots_%d,%d},' % (idv, call, i, len(ents)))
o.append('};')
o.append('#define SI_MESSAGES %d' % len(rows))
# small tables
def strarr(name, base, cnt):
    return 'static const char *const %s[%d]={%s};' % (name, cnt, ','.join(q(cstr(u32(base + 4 * i))) for i in range(cnt)))
o.append(strarr('si_area_window', 0x4cc830, 4))
o.append(strarr('si_line_select', 0x4cc840, 4))
o.append(strarr('si_line_on', 0x4cc850, 4))
o.append('static const struct {const char *sequence;int32_t slot;} si_card_rows5[5]={%s};' % ','.join(
    '{%s,%d}' % (q(cstr(u32(0x4cd060 + 8 * i))), s32(0x4cd060 + 8 * i + 4)) for i in range(5)))
o.append('static const struct {const char *sequence;int32_t slot;} si_card_rows2[2]={%s};' % ','.join(
    '{%s,%d}' % (q(cstr(u32(0x4cd090 + 8 * i))), s32(0x4cd090 + 8 * i + 4)) for i in range(2)))
o.append('static const float si_panel_position[4][3]={%s};' % ','.join(
    '{%s}' % ','.join(fl(f32(0x4cf640 + 12 * i + 4 * k)) for k in range(3)) for i in range(4)))
o.append('static const struct {const char *model,*open,*idle;} si_digimon[16]={%s};' % ','.join(
    '{%s,%s,%s}' % tuple(q(cstr(u32(0x4cec70 + 12 * i + 4 * k))) for k in range(3)) for i in range(16)))
# LoadIntf2 Create (state 4, MakeChr _chaSelDegi 0..3): the starters' preview models and player models
o.append(strarr('si_starter_preview', 0x4cd0d0, 4))
o.append(strarr('si_starter_model', 0x4cd0e0, 4))
# NameSel (3de260/3def80): the key rows {count; u16 codes[32]} at 4cc860, stride 0x44. _langID 1 (USA) uses rows 0..3.
keyrows = []
for r in range(0x1e):
    cnt = s32(0x4cc860 + 0x44 * r)
    keyrows.append('{%d,{%s}}' % (cnt, ','.join('0x%x' % struct.unpack('<H', rd(0x4cc864 + 0x44 * r + 2 * k, 2))[0] for k in range(32))))
o.append('static const struct {int32_t count;uint16_t code[32];} si_key_rows[%d]={%s};' % (len(keyrows), ','.join(keyrows)))
print('\n'.join(o))

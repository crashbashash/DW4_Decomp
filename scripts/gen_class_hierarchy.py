#!/usr/bin/env python3
"""gen_class_hierarchy.py — recover the real class hierarchy from the registrars.

The RTTI records cannot give the hierarchy: every `__RTTI__`'s `+4` word points at
`Gap::Core::igObject` for 578 of 579 records (see
`docs/engine/rtti-and-vtables.md`).  The reflection registrars can.  The third code
argument of `igMetaObject_RegisterClass` (`a3`, called "fn2") returns the **base
class's MetaObject**, and the registrar passes it straight to
`igMetaObject_InheritFromBase` — so

    fn2(X)()  ==  *(Y's MetaObject handle)   =>   Y is X's immediate base

`fn2(X)` is a small getter (`lui at,hi; lw v0,lo(at); jr ra`, reached through a
`j` thunk), so the handle it returns is read straight out of its body and mapped
back to a class through `data/reflection.json`.  That resolves **1,074 of 1,075**
classes; only `igObject` itself has no base.

This is the piece the vtable write-up says is missing: it identifies the
intermediate bases (`igAttr`, `igObjectList`, `igTObjectList<…>`) that have an
RTTI record but never an emitted vtable, which is what a shared vfunc default must
be attributed to.

Writes `data/class-hierarchy.tsv` (`class<TAB>base`, root first as `-`).

  scripts/gen_class_hierarchy.py [--elf PATH] [--out PATH]
"""
import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ELF = os.environ.get("DW4_ELF", os.path.join(ROOT, "orig", "SLUS-20836", "SLUS_208.36"))
VADDR_BASE, FILE_BASE = 0x100000, 0x80


def tracker():
    src = open(os.path.join(ROOT, "scripts", "dump_reflection.py")).read()
    ns = {}
    exec(src.replace("\nmain()\n", "\n"), ns)          # noqa: S102 (our own script)
    return ns


def returned_handle(img, fn):
    """The `*(handle)` address a small getter returns, or None."""
    for _ in range(4):                                  # follow `j` thunks
        w = img.u32(fn)
        if (w >> 26) == 0x02:
            fn = ((w & 0x03FFFFFF) << 2) | (fn & 0xF0000000)
            continue
        break
    for k in range(24):
        va = fn + k * 4
        w = img.u32(va)
        if (w >> 26) != 0x0F or ((w >> 16) & 31) != 1:  # lui at, hi
            continue
        hi = (w & 0xFFFF) << 16
        for j in range(1, 6):
            w2 = img.u32(va + j * 4)
            if (w2 >> 26) in (0x23, 0x27) and ((w2 >> 21) & 31) == 1:
                lo = w2 & 0xFFFF
                return hi + (lo - 0x10000 if lo >= 0x8000 else lo)
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--elf", default=ELF)
    ap.add_argument("--reflection", default=os.path.join(ROOT, "data", "reflection.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "data", "class-hierarchy.tsv"))
    a = ap.parse_args()

    classes = json.load(open(a.reflection))["classes"]
    by_handle = {int(c["handle"], 16): c["class"] for c in classes.values()}
    ns = tracker()
    elf = open(a.elf, "rb").read()
    buf = bytearray(elf[FILE_BASE:])
    lo = VADDR_BASE
    img = ns["Image"](lo, buf, lo + len(buf),
                      ns["_detect_codemax"](lo, buf, lo + len(buf)))

    base = {}
    for c in classes.values():
        regs, _stack = ns["resolve_call"](img, int(c["register_site"], 16))
        fn2 = regs.get(7)
        h = returned_handle(img, fn2) if isinstance(fn2, int) else None
        base[c["class"]] = by_handle.get(h) if h else None

    # depth check: every chain must reach the root without a cycle
    def depth(name, seen):
        b = base.get(name)
        if b is None:
            return 0
        assert b not in seen, "cycle at %s" % name
        return 1 + depth(b, seen | {name})

    depths = {n: depth(n, {n}) for n in base}
    lines = ["# Class hierarchy, recovered from the registrar's fn2 (base MetaObject).",
             "# GENERATED by scripts/gen_class_hierarchy.py; do not hand-edit.",
             "# class\tbase"]
    for name in sorted(base):
        lines.append("%s\t%s" % (name, base[name] or "-"))
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    open(a.out, "w").write("\n".join(lines) + "\n")
    roots = [n for n, b in base.items() if b is None]
    print("gen_class_hierarchy: %d classes, %d roots (%s), max depth %d -> %s"
          % (len(base), len(roots), ",".join(roots), max(depths.values()), a.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())

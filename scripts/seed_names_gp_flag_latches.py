#!/usr/bin/env python3
"""Name the 24-byte "set a gp-relative flag byte once" leaves after their libraries.

Every function with exactly this body:

    lbu  v1,off(gp)      ; load a byte flag
    bnez v1,.end         ; already set: leave it
    li   v1,1
    sb   v1,off(gp)      ; set it
    .end: jr ra ; nop

is a run-once latch. Each one heads a contiguous block of classes, and every class
registrar calls the latch of the block it sits in, as its first statement. There is
one latch per library, so a latch is named for the library its block holds.

  python3 scripts/seed_names_gp_flag_latches.py > config/SLUS-20836/names/GpFlagLatches.tsv
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHAPE = (0x93830000, 0x14600002, 0x24030001, 0xa3830000, 0x03e00008, 0x00000000)
MASK = (0xffff0000, 0xffffffff, 0xffffffff, 0xffff0000, 0xffffffff, 0xffffffff)
LIBRARIES = {
    0x00130000: "Attrs",
    0x00142f10: "Audio",
    0x00145ce0: "WindowInput",
    0x00194380: "SceneGraph",
    0x001e3ff0: "DataPump",
    0x00225770: "Base",
    0x00230f50: "Insight",
    0x00238d50: "SceneSearch",
    0x002393f0: "Collision",
    0x0023c440: "Lua",
    0x00334440: "AdxMovie",
    0x0033c8e0: "Bec",
    0x003b0a10: "Ndmw",
    0x0044b860: "Gui",
    0x00458680: "Viewer",
}


def main():
    data = open(os.path.join(ROOT, "orig/SLUS-20836/SLUS_208.36"), "rb").read()
    phoff, = struct.unpack_from("<I", data, 0x1c)
    phentsize, phnum = struct.unpack_from("<HH", data, 0x2a)
    segs = [struct.unpack_from("<8I", data, phoff + i * phentsize) for i in range(phnum)]
    segs = [(va, off, fs) for t, off, va, _p, fs, _m, _f, _a in segs if t == 1]
    syms = {}
    for ln in open(os.path.join(ROOT, "config/SLUS-20836/symbols.txt")):
        if not ln.startswith("#") and ln.strip():
            va, size, name = ln.split()[:3]
            syms[int(va, 16)] = (int(size, 16), name)
    thunked = {n[len("thunk_"):] for _, n in syms.values() if n.startswith("thunk_")}
    print("# GENERATED by scripts/seed_names_gp_flag_latches.py; do not edit.")
    print("# 24-byte lbu/bnez/li/sb flag latches, one per library; each library's registrars call it.")
    print("# <va>\t<name>\t<module>")
    for va, (size, name) in sorted(syms.items()):
        if size != 24 or name in thunked:
            continue
        for sva, off, fs in segs:
            if sva <= va < sva + fs:
                words = struct.unpack_from("<6I", data, off + va - sva)
                same_off = (words[0] & 0xffff) == (words[3] & 0xffff)
                if same_off and all(w & m == s for w, m, s in zip(words, MASK, SHAPE)):
                    mod = "game" if 0x330000 <= va < 0x480000 else "engine"
                    print("0x%08x\t%sLibrary_MarkRegistered\t%s" % (va, LIBRARIES[va], mod))


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""gen_platform_seam.py — the platform seam: which generic interfaces the `igPsx2*` classes sit under.

The engine is written against *generic* platform classes and the PS2 implementations sit underneath
them.  The engine logic above the generic side does not depend on the PS2.  This script recovers the seam as an inventory instead of leaving it as a
claim:

  * `data/class-hierarchy.tsv` gives each class's base, so every `igPsx2*` class yields the generic
    class it derives from (`igPsx2File -> igFile`, `igPsx2VisualContext -> igVisualContext`, ...);
  * `data/reflection.json` gives that base's fields with real names, offsets and metafield types, so
    the interface's state is recovered rather than invented;
  * `igPsx2IopRpcConnection` is the one exception -- it derives from `igObject`, not from a generic
    interface: it is the seam itself.

    scripts/gen_platform_seam.py                       # report
    scripts/gen_platform_seam.py --out docs/engine/platform-seam.md
    scripts/gen_platform_seam.py --check               # for `make rules`
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")


def load():
    R = json.load(open(os.path.join(ROOT, "data", "reflection.json")))
    by = {v["class"]: v for v in R["classes"].values()}
    base = {}
    for line in open(os.path.join(ROOT, "data", "class-hierarchy.tsv")):
        if line.startswith("#"):
            continue
        p = line.rstrip("\n").split("\t")
        if len(p) >= 2:
            base[p[0]] = p[1]
    return by, base


def seam():
    """[(igPsx2 class, generic base, base fields)] plus the ones that are not under an interface."""
    by, base = load()
    psx = sorted(c for c in by if c.startswith("igPsx2"))
    rows, odd = [], []
    for c in psx:
        b = base.get(c)
        if b is None or b == "igObject":
            odd.append((c, b))
            continue
        f = by.get(b)
        rows.append((c, b, f["fields"] if f else []))
    return rows, odd, by


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out")
    ap.add_argument("--check", action="store_true",
                    help="fail if the generated doc is stale (for `make rules`)")
    ap.add_argument("--default-out", default="docs/engine/platform-seam.md")
    args = ap.parse_args()

    rows, odd, by = seam()
    bases = sorted({b for _c, b, _f in rows})
    nfields = sum(len(f) for _c, _b, f in rows)
    print("platform seam: %d igPsx2* class(es) -> %d generic interface(s), %d field(s)"
          % (len(rows), len(bases), nfields))
    print("not under a generic interface (the RPC seam): %s" % (odd,))

    out = []
    w = out.append
    w("# The platform seam\n")
    w("_Generated by `scripts/gen_platform_seam.py` -- do not hand-edit._\n")
    w("The engine is written against **generic** platform classes and the PS2 implementations sit "
      "underneath them. The seam is recovered from the data rather than asserted: "
      "`data/class-hierarchy.tsv` gives each class's base, and `data/reflection.json` gives that "
      "base's fields with names, offsets and metafield types.\n")
    w("**%d `igPsx2*` classes sit under %d generic interfaces carrying %d fields.** %s\n"
      % (len(rows), len(bases), nfields,
         ("The exception is `%s`, which derives from `%s` instead -- that is the RPC seam itself." % (odd[0][0], odd[0][1])) if odd else ""))
    w("## The interfaces\n")
    w("| `igPsx2*` implementation | generic interface | fields |")
    w("| --- | --- | --- |")
    for c, b, f in rows:
        w("| `%s` | **`%s`** | %d |" % (c, b, len(f)))
    w("")
    w("## What each interface holds\n")
    w("Everything below is the recovered field list (`offset name : metafield type`).\n")
    for b in bases:
        f = by.get(b, {}).get("fields", [])
        w("### `%s`" % b)
        if not f:
            w("\n_no fields serialised_.\n")
            continue
        w("")
        w("| offset | field | metafield type |")
        w("| --- | --- | --- |")
        for fl in sorted(f, key=lambda x: x["offset"]):
            w("| +%d | `%s` | `%s` |" % (fl["offset"], fl["name"], fl.get("type", "?")))
        w("")
    text = "\n".join(out)
    if args.check:
        cur = open(os.path.join(ROOT, args.default_out)).read()
        if cur != text:
            print("gen_platform_seam: %s is STALE -- regenerate" % args.default_out)
            return 1
        print("gen_platform_seam: %s is current" % args.default_out)
        return 0
    if args.out:
        open(os.path.join(ROOT, args.out), "w").write(text)
        print("wrote %s" % args.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""Inventory direct retail dependencies of the 116 Lua API implementations.

Reads the private ELF, canonical symbol extents and source definitions. Indirect
transfers remain explicit frontiers, not inferred edges or proof of completeness.
Run from the repository root; generated output contains no binary extracts.
"""
import argparse
import bisect
from collections import deque
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import units
import verify


def transfers(code, start):
    """Return direct target sites and unresolved register transfers.

    Include branch-and-link and external ordinary branches as well as J/JAL.
    Internal branches and JR RA are local control flow, not dependencies.
    """
    direct, indirect = [], []
    end = start + len(code)
    for i in range(0, len(code), 4):
        word, = struct.unpack_from("<I", code, i)
        pc, op = start + i, word >> 26
        target = None
        if op in (2, 3):
            target = ((pc + 4) & 0xf0000000) | ((word & 0x3ffffff) << 2)
        elif (op in (4, 5, 6, 7, 20, 21, 22, 23)
              or (op == 1 and ((word >> 16) & 31) in (0, 1, 2, 3, 16, 17, 18, 19))
              or (op in (16, 17, 18) and ((word >> 21) & 31) == 8)):
            delta = word & 0xffff
            target = pc + 4 + ((delta if delta < 0x8000 else delta - 0x10000) << 2)
        elif op == 0 and (word & 63) in (8, 9):
            reg = (word >> 21) & 31
            if (word & 63) == 9 or reg != 31:
                indirect.append({"site": pc, "kind": "jalr" if (word & 63) == 9 else "jr", "register": reg})
        if target is not None and not start <= target < end:
            direct.append({"site": pc, "target": target})
    return direct, indirect


def inventory(elf):
    image = verify.read_elf(str(elf))
    _, symbols = verify.load_symbols(str(ROOT / "config/SLUS-20836/symbols.txt"))
    starts = sorted(symbols)
    sources = units.scan(str(ROOT / "src"))
    apis = json.loads((ROOT / "data/script_api.json").read_text())
    assert len(apis) == 116 and len({row["real"] for row in apis}) == 116
    reviewed = []
    for line in (ROOT / "config/SLUS-20836/lua-dependency-roots.tsv").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        address, evidence = line.split("\t", 1)
        reviewed.append({"address": int(address, 0), "evidence": evidence})
    if len({row["address"] for row in reviewed}) != len(reviewed):
        raise ValueError("duplicate reviewed dependency root")
    roots = {row["real"] for row in apis} | {0x370780, 0x3719d0} | {row["address"] for row in reviewed}
    queue, reached, records = deque(sorted(roots)), set(), {}
    while queue:
        va = queue.popleft()
        if va in reached:
            continue
        reached.add(va)
        if va not in symbols:
            raise ValueError(f"missing root/dependency symbol {va:#x}")
        name, size = symbols[va]
        direct, indirect = transfers(verify.va_bytes(image, va, size), va)
        for edge in direct:
            target = edge["target"]
            i = bisect.bisect_right(starts, target) - 1
            owner = starts[i] if i >= 0 else None
            if owner is not None and target < owner + symbols[owner][1]:
                edge["function"] = owner
                edge["entry_offset"] = target - owner
                queue.append(owner)
            else:
                edge["function"] = None
        source = sources.get(name)
        records[va] = {"address": va, "name": name, "size": size,
                       "source": str(Path(source).relative_to(ROOT)) if source else None,
                       "direct": direct, "indirect": indirect}
    rows = [records[va] for va in sorted(records)]
    return {"roots": [{"id": row["id"], "api": row["name"], "address": row["real"]} for row in apis],
            "infrastructure_roots": [0x370780, 0x3719d0], "reviewed_roots": reviewed, "functions": rows}


def render(data):
    rows = data["functions"]
    total = sum(r["size"] for r in rows)
    recovered = sum(r["size"] for r in rows if r["source"])
    by_va = {r["address"]: r for r in rows}
    lines = ["# Lua engine dependency inventory", "",
             "Generated by `python3 scripts/lua_engine_dependencies.py --write`; do not edit by hand.", "",
             "This is a static lower bound rooted at all 116 bound API implementations, plus",
             "Lua registration/dispatch and the reviewed producer/receiver roots below.",
             "Edges come from retail instructions, including",
             "direct tail transfers. Interior targets retain their entry offsets in the JSON.", "",
             f"The direct closure contains **{len(rows):,} functions / {total:,} code bytes**;",
             f"**{sum(bool(r['source']) for r in rows):,} functions / {recovered:,} bytes** have source definitions in `src/`.",
             "Source presence is not a fresh byte-verification result: run `make check` and `make link`.", "",
             f"There are **{sum(len(r['indirect']) for r in rows):,} unresolved register-transfer sites** and",
             f"**{sum(e['function'] is None for r in rows for e in r['direct']):,} direct sites outside known function extents**.", "",
             "This is not the complete gameplay dependency graph. Virtual dispatch, SD receiver",
             "selection, Lua callbacks, queued updates and data-held function pointers require",
             "separate evidence. A switch's register jump also appears as an unresolved frontier.",
             "The closure includes platform/middleware code; presence does not mean it should",
             "be ported instead of replaced at its documented platform boundary.", "",
             "Machine-readable edges and unresolved sites: [`../../data/lua-dependencies.json`](../../data/lua-dependencies.json).", "",
             "## Reviewed producer/receiver roots", "",
             "These explicitly evidenced roots extend the direct closure through queued/virtual",
             "entry points without attributing an invented call edge to a generic dispatcher.", "",
             "| Address | Evidence |", "| --- | --- |"]
    for row in data["reviewed_roots"]:
        lines.append(f"| `0x{row['address']:08x}` | {row['evidence']} |")
    lines += ["", "## Bound API recovery", "", "| ID | Lua API | Retail implementation | Matching source |", "| --- | --- | --- | --- |"]
    for root in data["roots"]:
        row = by_va[root["address"]]
        source = f"[`{row['source']}`](../../{row['source']})" if row['source'] else "assembly only"
        lines.append(f"| {root['id']} | `{root['api']}` | `0x{row['address']:08x}` | {source} |")
    lines += ["", "## Direct engine dependencies still in assembly", "",
              "This address-ordered queue covers the game/engine region from the documented",
              "module map, not arbitrary byte-yield targets. Recover contiguous modules and",
              "their indirect frontiers before claiming a subsystem complete.", "",
              "| Address | Symbol | Bytes | Indirect sites |", "| --- | --- | ---: | ---: |"]
    for row in rows:
        if row["address"] >= 0x334000 and not row["source"]:
            lines.append(f"| `0x{row['address']:08x}` | `{row['name']}` | {row['size']} | {len(row['indirect'])} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--elf", type=Path, default=ROOT / "orig/SLUS-20836/SLUS_208.36")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = inventory(args.elf)
    outputs = {ROOT / "data/lua-dependencies.json": json.dumps(data, indent=2) + "\n",
               ROOT / "docs/engine/lua-dependencies.md": render(data)}
    for path, contents in outputs.items():
        if args.write:
            path.write_text(contents)
        if args.check and (not path.exists() or path.read_text() != contents):
            raise SystemExit(f"stale generated output: {path.relative_to(ROOT)}")
    print(render(data).split("## Bound API recovery")[0])


if __name__ == "__main__":
    main()

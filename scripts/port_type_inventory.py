#!/usr/bin/env python3
"""Generate port/docs/arena-migration-backlog.md: which port modules still use the host-native game types.

The arena object model (port/docs/arena-object-model.md) replaces the port's host-private game data with the decomp's
authoritative structs held in arena memory. This counts, per `port/src/*.c` module, the uses of each host-native type family so
the migration follows real dependencies:

  property  dw4_property_* / dw4_playerrecords  (named-value folders: the player, common and item records; retail beDataObjList)
  object    dw4_object*                         (host instance bytes + borrowed strings: the stage-object registry)
  stageobj  dw4_stageobject*                    (the prepared scene registry over dw4_object)
  database  dw4_database*                       (already typed arena tables; counts are accessor calls, not a type)
  arena     dw4_arena* / dw4_adb* / dw4_dbtable (already migrated)

Usage: scripts/port_type_inventory.py [--check]   (--check exits 1 when the committed page is stale)
"""
import glob
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "port", "docs", "arena-migration-backlog.md")
FAMILIES = [
    ("property", r"\bdw4_property_\w+|\bdw4_playerrecords\w*"),
    ("object", r"\bdw4_object(?:_(?!init_header\b)\w+)?\b"),
    ("stageobj", r"\bdw4_stageobject\w*"),
    ("database", r"\bdw4_database\w*"),
    ("arena", r"\bdw4_arena\w*|\bdw4_adb\w*|\bdw4_dbtable\b"),
]


def render():
    rows = []
    for path in sorted(glob.glob(os.path.join(ROOT, "port", "src", "*.c"))):
        text = open(path, errors="replace").read()
        counts = {k: len(re.findall(p, text)) for k, p in FAMILIES}
        rows.append((os.path.basename(path), text.count("\n"), counts))
    tot = {k: sum(r[2][k] for r in rows) for k, _ in FAMILIES}
    out = ["# Arena migration backlog", "",
           "Generated by `scripts/port_type_inventory.py`; do not edit. Which `port/src` modules still use the host-native game types the",
           "[arena object model](arena-object-model.md) replaces. A module leaves a column when its last use moves onto typed arena objects.",
           "", "| family | uses | modules | retail counterpart |", "| --- | ---: | ---: | --- |"]
    meaning = {
        "property": "`beDataObjList` of named `beDataObj*` records (`_data` at +12) in the session arena (**done**: the `dw4_property_*` accessors read and write typed trees)",
        "object": "the reflected instance itself (`reflected.h` struct in the arena). What remains is the host record decoder `dw4_object`, a loader helper that reads one pack record and discards it (not game state)",
        "stageobj": "the pack's objects as arena instances (**done**: infos load shallowly into the session arena; typed `dw4_stageobject_*` accessors)",
        "database": "`beDataBase` typed tables (**done**: accessors read the arena)",
        "arena": "(**migrated**)",
    }
    for k, _ in FAMILIES:
        out.append("| `%s` | %d | %d | %s |" % (k, tot[k], sum(1 for r in rows if r[2][k]), meaning[k]))
    out += ["", "## Modules that still call the host record decoder", "",
            "These read a pack record into a transient `dw4_object` and discard it; no game state is held in one. Lines are source lines.", "",
            "| module | lines | dw4_object uses |", "| --- | ---: | ---: |"]
    pending = [r for r in rows if r[2]["object"]]
    pending.sort(key=lambda r: -r[2]["object"])
    for name, lines, c in pending:
        out.append("| `%s` | %d | %d |" % (name, lines, c["object"]))
    out += ["", "%d of %d modules use the decoder." % (len(pending), len(rows)), ""]
    return "\n".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        return 0 if os.path.exists(OUT) and open(OUT).read() == text else 1
    open(OUT, "w").write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())

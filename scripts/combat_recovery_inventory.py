#!/usr/bin/env python3
"""Inventory the retail FIGHTCALC switch, direct calls and combat Lua helpers.

This is a matching-recovery queue, not a combat-completion percentage. The
switch cases share the GAMERAM function's frame and epilogue; they are not
independent functions. Source presence is checked separately by make check.
"""
import argparse
import json
import os
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import units

DISPATCHER = 0x3FCA10
FIGHT_START, FIGHT_END = 0x3FDE30, 0x406AD0
NAMES, VALUES, TARGETS = 0x4CC350, 0x4CC3B0, 0x519310
COUNT = 22
JSON_PATH = ROOT / "data/combat-recovery.json"
DOC_PATH = ROOT / "docs/systems/combat-inventory.md"


def inventory(elf):
    image = Path(elf).read_bytes()

    def word(address):
        return struct.unpack_from("<I", image, address - 0x100000 + 0x80)[0]

    def string(address):
        offset = address - 0x100000 + 0x80
        return image[offset:image.index(b"\0", offset)].decode("ascii")

    symbols = {}
    for line in (ROOT / "config/SLUS-20836/symbols.txt").read_text().splitlines():
        if line and not line.startswith("#"):
            address, size, name, *_ = line.split()
            symbols[int(address, 16)] = (int(size, 16), name)
    source = units.scan(str(ROOT / "src"))

    def function(address):
        size, name = symbols[address]
        path = source.get(name)
        return {"address": f"0x{address:08x}", "name": name, "size": size,
                "source": str(Path(path).relative_to(ROOT)) if path else None}

    # Check the parent command and both table lengths against retail, rather
    # than silently attributing another receiver's cases to FIGHTCALC.
    if (string(word(0x4CC410 + 18 * 4)) != "FIGHTCALC"
            or word(0x519370 + 18 * 4) != FIGHT_START
            or word(0x519370 + 20 * 4) != FIGHT_END
            or word(0x3FCA60) != 0x2C410016
            or word(0x3FDE90) != 0x2C410016):
        raise ValueError("retail FIGHTCALC boundary/dispatch guard differs")
    cases = []
    for i in range(COUNT):
        target = word(TARGETS + i * 4)
        if word(VALUES + i * 4) != i or not FIGHT_START <= target < FIGHT_END:
            raise ValueError(f"invalid combat switch entry {i}")
        cases.append({"id": i, "command": string(word(NAMES + i * 4)),
                      "target": f"0x{target:08x}"})
    calls, indirect = {}, []
    for address in range(FIGHT_START, FIGHT_END, 4):
        instruction = word(address)
        if instruction >> 26 == 3:
            target = ((address + 4) & 0xF0000000) | ((instruction & 0x3FFFFFF) << 2)
            if target not in symbols:
                raise ValueError(f"unclassified direct callee at {address:#x}: {target:#x}")
            calls.setdefault(target, []).append(f"0x{address:08x}")
        elif instruction >> 26 == 0 and instruction & 0x3F == 9:
            indirect.append(f"0x{address:08x}")
    direct = [dict(function(address), sites=sites) for address, sites in sorted(calls.items())]
    wrappers = [function(address) for address in sorted(symbols)
                if 0x374800 <= address < 0x375D90]
    return {"scope": "FIGHTCALC physical switch region and direct-call lower bound",
            "dispatcher": function(DISPATCHER),
            "region": {"start": f"0x{FIGHT_START:08x}",
                       "end_exclusive": f"0x{FIGHT_END:08x}",
                       "size": FIGHT_END - FIGHT_START},
            "cases": cases, "direct_callees": direct,
            "indirect_call_sites": indirect, "lua_helpers": wrappers}


def render(data):
    dispatcher, region = data["dispatcher"], data["region"]
    lines = ["# Combat calculation recovery inventory", "",
             "Generated by `python3 scripts/combat_recovery_inventory.py --write`; do not edit.", "",
             f"FIGHTCALC occupies **{region['size']:,} bytes** at `{region['start']}`–"
             f"`{region['end_exclusive']}` (exclusive), inside the **{dispatcher['size']:,}-byte**",
             f"GAMERAM dispatcher `{dispatcher['address']}`. These bytes overlap the dispatcher;",
             "do not add the two totals. Cases share its stack frame and epilogue.", "",
             f"Dispatcher matching source: **{dispatcher['source'] or 'assembly only'}**.", "",
             "This is a direct-call lower bound, not a percentage of all combat recovered.",
             "Indirect calls, hit geometry, actor programs, spawning and progression need",
             "their own recovery. Source presence does not substitute for `make check`.", "",
             "## Switch commands", "", "| Id | Command | Retail target |",
             "| ---: | --- | --- |"]
    lines += [f"| {r['id']} | `{r['command']}` | `{r['target']}` |" for r in data["cases"]]
    for key, title in [("lua_helpers", "Contiguous combat Lua helper run"),
                       ("direct_callees", "Direct callees from the FIGHTCALC region")]:
        rows = data[key]
        matched = [r for r in rows if r["source"]]
        lines += ["", f"## {title}", "",
                  f"{len(matched)}/{len(rows)} bodies have matching source definitions "
                  f"({sum(r['size'] for r in matched):,}/{sum(r['size'] for r in rows):,} bytes).",
                  "", "| Address | Function | Bytes | Matching source |",
                  "| --- | --- | ---: | --- |"]
        lines += [f"| `{r['address']}` | `{r['name']}` | {r['size']} | "
                  + (f"[{r['source']}](../../{r['source']})" if r["source"] else "assembly only")
                  + " |" for r in rows]
    lines += ["", f"The region also contains **{len(data['indirect_call_sites'])} indirect call sites**",
              "(`jalr`); these are listed in `data/combat-recovery.json`. The switch's",
              "indirect jump is not counted as a call.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--elf", default=os.environ.get("DW4_ELF", ROOT / "orig/SLUS-20836/SLUS_208.36"))
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = inventory(args.elf)
    outputs = {JSON_PATH: json.dumps(data, indent=2) + "\n", DOC_PATH: render(data)}
    for path, text in outputs.items():
        if args.write:
            path.write_text(text)
        elif args.check and (not path.exists() or path.read_text() != text):
            raise SystemExit(f"stale inventory: {path.relative_to(ROOT)}")
    if not args.write and not args.check:
        print(outputs[DOC_PATH], end="")


if __name__ == "__main__":
    main()

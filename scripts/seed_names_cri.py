#!/usr/bin/env python3
"""CRI ADX and Sofdec function names, in CRI's own spelling.

Reads `data/cri-names-worklist.tsv` (one row per function: address, name, confidence and the
evidence tokens) and writes the two overlays `tools/split.py` merges over the dump:

  config/SLUS-20836/names/CriAdx.tsv      functions below 0x27ede0 (the `cri-adx` block)
  config/SLUS-20836/names/CriSofdec.tsv   functions from 0x280b98 (the `cri-sofdec` block)

Each overlay row is `<va> <name> cri <confidence> <evidence>`. The names come from CRI's PS2 SDK
archives (libadxe.a, libmwsfde.a: https://github.com/SkeletonPicture/recvx-decomp-cri) and from the
Street Fighter III 3rd Strike libadxe (https://github.com/crowded-street/3s-decomp); both are cited, never
vendored. What makes a row high or medium is in docs/engine/naming.md.

  python3 scripts/seed_names_cri.py            # write both overlays
  python3 scripts/seed_names_cri.py --check    # fail when either overlay differs from the worklist
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WORKLIST = os.path.join(ROOT, "data", "cri-names-worklist.tsv")
NAMES = os.path.join(ROOT, "config", "SLUS-20836", "names")
ADX_END = 0x27EDE0

SDK_URL = "github.com/SkeletonPicture/recvx-decomp-cri"
TS_URL = "github.com/crowded-street/3s-decomp"

HEADER = """# CRI %s function names, in CRI's own spelling. GENERATED by scripts/seed_names_cri.py from
# data/cri-names-worklist.tsv; do not edit.
# Columns: <va>  <name>  <module>  <confidence>  <evidence>. tools/split.py reads the first three.
# Sources: the CRI PS2 SDK archives libadxe.a / libmwsfde.a (recvx-decomp-cri, %s) and the
# Street Fighter III 3rd Strike libadxe (3s-decomp, %s). Tier: A masked-exact body, B/C near body
# after address masking, O same position in order with equal size. A medium row is a fair reading
# where another name is plausible; the alternative is in the evidence.
"""


def evidence(raw):
    """Spell the worklist tokens as source names and append the URLs of the sources used."""
    text = re.sub(r"sdk:(lib\w+\.a)/(\S+)", r"recvx-decomp-cri \1 \2", raw)
    text = re.sub(r"3s:(\w+)", r"3s-decomp \1", text)
    text = re.sub(r" \((?:sdk|3s) - -\)", "", text)
    text = re.sub(r"\((sdk|3s) (\w+) (\w)\)", r"(\1 proposes \2, tier \3)", text)
    urls = []
    if "recvx-decomp-cri" in text:
        urls.append("recvx-decomp-cri " + SDK_URL)
    if "3s-decomp" in text:
        urls.append("3s-decomp " + TS_URL)
    return text + (" [" + "; ".join(urls) + "]" if urls else "")


def render():
    rows = {"CriAdx": [], "CriSofdec": []}
    for line in open(WORKLIST):
        if line.startswith("#") or not line.strip():
            continue
        va, name, conf, raw = line.rstrip("\n").split("\t")
        addr = int(va, 16)
        rows["CriAdx" if addr < ADX_END else "CriSofdec"].append(
            "0x%08x\t%s\tcri\t%s\t%s\n" % (addr, name, conf, evidence(raw)))
    out = {}
    for stem, title in (("CriAdx", "ADX"), ("CriSofdec", "Sofdec")):
        out[stem] = HEADER % (title, SDK_URL, TS_URL) + "".join(rows[stem])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    bad = 0
    for stem, text in render().items():
        path = os.path.join(NAMES, stem + ".tsv")
        if args.check:
            if not os.path.exists(path) or open(path).read() != text:
                print("%s is out of date: run scripts/seed_names_cri.py" % path, file=sys.stderr)
                bad = 1
        else:
            with open(path, "w") as f:
                f.write(text)
    return bad


if __name__ == "__main__":
    sys.exit(main())

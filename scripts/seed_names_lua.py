#!/usr/bin/env python3
"""seed_names_lua.py — emit the Lua native-API name block for config/SLUS-20836/names/Lua.tsv.

The 116 functions scripts can call (`be:SYSgetPlayerLevel()` and friends) are
already decoded in `data/script_api.json` and written up in
`docs/engine/script-engine-lua.md`: every entry has the API `name`, the dispatcher
`stub` it routes through and the C++ `real` implementation that stub calls.

This emits one overlay line per **real implementation**, plus the two functions the
write-up names directly: the dispatcher at `0x00370780` and the registration entry
point at `0x003719d0`, the `be` class's `registerFunctions`.  Names are the API name
itself; where the table uses one name for several entries (the API overloads — `sd`,
`DMsetSD`, `DMchkSD`, `DMswtSD`, `MDLsetWorldPosTarget`) each gets its table `id` as a
suffix, so no two addresses claim the same name.

The 116 **stubs are not nameable individually**: they are all branch targets
*inside* the single 4,192-byte function at `0x00370780` (auto-analysis made the
dispatcher and its stub table one function), so `config/SLUS-20836/symbols.txt` has no symbol
for them.  Carving that function up is a separate, larger change.  The same is true
of the other addresses the write-up mentions (`beModelCtrlLUACALL`,
`SHOW_LUACALL`/`HIDE_LUACALL`, `_isLuaCallDisp`): they are not symbol starts.

  scripts/seed_names_lua.py > config/SLUS-20836/names/Lua.tsv
"""
import collections
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# Functions the write-up names directly, as opposed to the 116 in the API table.
FIXED = [(0x00370780, "LuaAPI_Dispatch"),                    # the dispatcher (its stubs live inside)
         (0x003719d0, "beLuaWrapper::registerFunctions")]   # calls the generic registrar


def main():
    data = json.load(open(os.path.join(ROOT, "data", "script_api.json")))
    seen = collections.Counter(e["name"] for e in data)
    rows = list(FIXED)
    for e in data:
        name = e["name"] if seen[e["name"]] == 1 else "%s_%d" % (e["name"], e["id"])
        rows.append((e["real"], name))
    assert len({va for va, _ in rows}) == len(rows), "duplicate address"
    assert len({n for _, n in rows}) == len(rows), "duplicate name"
    print("# Lua native API — the 116 functions bound to scripts.")
    print("# GENERATED by scripts/seed_names_lua.py from data/script_api.json; do not hand-edit.")
    print("# See docs/engine/script-engine-lua.md.  The dispatcher and its 116 stubs are")
    print("# one function (0x00370780), so only the dispatcher, the registration entry")
    print("# point and the 116 real implementations have a symbol to name.")
    print("# <va>\t<name>\t<module>")
    for va, name in sorted(rows):
        print("0x%08x\t%s\tLua" % (va, name))
    return 0


if __name__ == "__main__":
    sys.exit(main())

#!/usr/bin/env python3
"""
exceptions.py — find the retail C++ exception index records and record them.

MWCCPS2 emits, for every function of a translation unit compiled with
`-Cpp_exceptions on` (the compiler's default), one 12-byte **index record** in
`.exceptix` and, when the function has cleanup actions, an **exception table**
in `.exception` (docs/engine/exception-unwind.md):

    word 0  function address              (R_MIPS_32 against the function)
    word 1  code size, bit 0 set when word 2 is the packed inline form
    word 2  table address (R_MIPS_32 against the unit's `.exception` section)
            or the packed inline form (saved-register/frame summary, no table)

The retail linker concatenated every unit's `.exceptix` into one array of
records in link order (`0x546fb0..0x554858`, 4,622 records) and every
`.exception` into the table region just before it (`0x542ae0..0x546fb0`).
Neither has a section name in the flat retail ELF, so from the source and the
symbol map alone the records are invisible: a C++ unit could "verify" on its
code while its index record and table were never looked at, and the relink
would orphan them. This tool recovers them from the retail image:

  * a record is a 4-aligned triple whose first word is an image address,
    whose code size is plausible and whose third word is either packed or an
    address inside the image;
  * records are read as runs of consecutive triples; a run counts only when
    enough of its records name a function of `config/SLUS-20836/symbols.txt` with exactly
    that size (a random data triple cannot do this four times in a row);
  * a table runs from its address to the next table's address; the last
    table ends where the index region begins, minus whole zero words of
    alignment padding. That last rule assumes the table ends on a nonzero
    word (retail's does: a destructor address); a last table that is only a
    header and a zero range terminator would come out a word short and its
    unit would fail verification rather than pass unseen.

The result is `config/SLUS-20836/exceptions.txt`: `fn_va index_record_va table_va
table_size` in hex, `-` when the record is packed and has no table.
`tools/verify.py` compares the compiled record and table of every unit against
these retail bytes, and `tools/linkgen.py` places them at the retail addresses.

Usage:
  exceptions.py --write      # regenerate config/SLUS-20836/exceptions.txt
  exceptions.py --check      # fail if config/SLUS-20836/exceptions.txt is stale
  exceptions.py --report     # census, write nothing
"""
import argparse
import os
import struct
import sys
from functools import lru_cache

VADDR_BASE, FILE_BASE = 0x100000, 0x80
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
ELF_DEFAULT = os.environ.get("DW4_ELF", os.path.join(ROOT, "orig", "SLUS-20836", "SLUS_208.36"))
SYMBOLS_DEFAULT = os.path.join(ROOT, "config", "SLUS-20836", "symbols.txt")
CONFIG_DEFAULT = os.path.join(ROOT, "config", "SLUS-20836", "exceptions.txt")
RECORD = 12
MIN_ANCHORS = 4             # symbol-backed records a run needs to count
MAX_CODE = 0x100000         # no function is a megabyte

HEADER = """# fn_va index_record_va table_va table_size — GENERATED by tools/exceptions.py; do not edit.
# The C++ exception metadata the retail linker kept for every function compiled
# with exceptions on: a 12-byte index record (function, code size, table or
# packed form) and, for functions with cleanup actions, an exception table.
# `-` marks a packed record without a table. tools/verify.py compares every
# compiled unit's record and table against these retail bytes and
# tools/linkgen.py places them at these addresses (docs/engine/exception-unwind.md).
"""


def read_functions(symbols):
    """config/SLUS-20836/symbols.txt -> {va: size}."""
    out = {}
    with open(symbols) as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            parts = line.split()
            out[int(parts[0], 16)] = int(parts[1], 16)
    return out


def scan(image, functions, base=VADDR_BASE, file_base=FILE_BASE):
    """-> sorted [(fn_va, index_va, table_va or None, table_size)] from a retail image.

    `image` is the whole ELF file; `functions` maps function address -> size.
    """
    lo, hi = base, base + len(image) - file_base
    words = struct.unpack_from("<%dI" % ((len(image) - file_base) // 4), image, file_base)

    def candidate(at):
        """The record at va `at`, or None when the triple cannot be one."""
        i = (at - base) // 4
        if i + 3 > len(words):
            return None
        fn, size, third = words[i], words[i + 1], words[i + 2]
        if not lo <= fn < hi or fn % 4 or not 4 <= size < MAX_CODE:
            return None
        # A packed third word is a register/frame summary (0x2000, 0x406000, ...)
        # with no shape to test; the run's anchors carry the proof instead.
        if not size & 1 and (not lo <= third < hi or third % 4):
            return None
        return (fn, at, None if size & 1 else third, size)

    def anchored(record):
        return functions.get(record[0]) == (record[3] & ~1)

    records, at = [], base
    while at + RECORD <= hi:
        run = []
        here = at
        while True:
            record = candidate(here)
            if record is None:
                break
            run.append(record)
            here += RECORD
        if sum(anchored(r) for r in run) >= MIN_ANCHORS:
            records.extend(run)
            at = here
        else:
            at += 4
    records.sort(key=lambda r: r[1])
    return _size_tables(records, image, base, file_base)


def _size_tables(records, image, base, file_base):
    """Replace the raw size word by the table's byte size (0 for a packed record)."""
    if not records:
        return []
    tables = sorted({r[2] for r in records if r[2] is not None})
    index_start = min(r[1] for r in records)
    sizes = {}
    for address, following in zip(tables, tables[1:] + [None]):
        if following is not None:
            sizes[address] = following - address
            continue
        if address >= index_start:
            raise ValueError("the last exception table does not precede the index region")
        end = index_start
        while end - 4 > address and not any(image[end - 4 - base + file_base:end - base + file_base]):
            end -= 4
        sizes[address] = end - address
    return [(fn, at, table, sizes[table] if table is not None else 0)
            for fn, at, table, _ in records]


def format_table(records):
    lines = [HEADER]
    for fn, at, table, size in records:
        lines.append("%08x %08x %s %s" % (fn, at, "%08x" % table if table is not None else "-",
                                          "%06x" % size if table is not None else "-"))
    return "\n".join(lines) + "\n"


@lru_cache(maxsize=8)
def load(path=None):
    """config/SLUS-20836/exceptions.txt -> {fn_va: (index_va, table_va or None, table_size)}.

    An absent file loads as an empty mapping so that a checkout without the
    generated table degrades to "no retail record known" rather than crashing;
    `make check` regenerates it. Cached and read-only by contract.
    """
    path = path or CONFIG_DEFAULT
    out = {}
    if not os.path.exists(path):
        return out
    with open(path) as fh:
        for line in fh:
            if line.startswith("#") or not line.strip():
                continue
            fn, at, table, size = line.split()
            out[int(fn, 16)] = (int(at, 16),
                                None if table == "-" else int(table, 16),
                                0 if size == "-" else int(size, 16))
    return out


def config_path(symbols=None):
    """The exception table that belongs to a symbol map (so --symbols still works).

    The repository's map uses config/SLUS-20836/exceptions.txt; any other map (a test
    fixture's) uses the `exceptions.txt` beside it, which may not exist — then
    no retail record is known for that image and the cross-checks do not apply.
    """
    if symbols is None or os.path.realpath(symbols) == os.path.realpath(SYMBOLS_DEFAULT):
        return CONFIG_DEFAULT
    return os.path.join(os.path.dirname(os.path.abspath(symbols)), "exceptions.txt")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--elf", default=ELF_DEFAULT)
    ap.add_argument("--symbols", default=SYMBOLS_DEFAULT)
    ap.add_argument("--out", default=CONFIG_DEFAULT)
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true", help="exit 1 if --out is stale")
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args(argv)
    with open(a.elf, "rb") as fh:
        image = fh.read()
    functions = read_functions(a.symbols)
    records = scan(image, functions)
    text = format_table(records)
    packed = sum(1 for r in records if r[2] is None)
    known = sum(1 for r in records if r[0] in functions)
    lo = min(r[1] for r in records) if records else 0
    hi = max(r[1] for r in records) + RECORD if records else 0
    print("exceptions: %d index records at 0x%x..0x%x (%d name a function of the symbol map), "
          "%d packed, %d with a table (%d table bytes)"
          % (len(records), lo, hi, known, packed, len(records) - packed,
             sum(r[3] for r in records)))
    if a.check:
        current = open(a.out).read() if os.path.exists(a.out) else ""
        if current != text:
            print("exceptions: %s is stale; run tools/exceptions.py --write" % a.out, file=sys.stderr)
            return 1
        print("exceptions: %s is current" % a.out)
    if a.write:
        with open(a.out, "w") as fh:
            fh.write(text)
        print("exceptions: wrote %s" % a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""unitprofiles.py — one build profile per translation unit (config/SLUS-20836/units.tsv).

The retail ELF was linked from translation units, and a compiler, a flag set and an
exception mode belong to a unit, never to one function: every function of a unit was
compiled by the same command. `config/SLUS-20836/units.tsv` records that profile once per unit,
and every tool that compiles a function (tools/verify.py, tools/check.py,
tools/linkgen.py) asks this module which profile applies to an address.

The table (generated by tools/gen_unit_profiles.py, reviewed and committed) has two
kinds of row, tab-separated:

    @compiler\t<id>\t<repository-relative executable>\t<SHA-256>
    <lo>\t<hi>\t<name>\t<compiler id>\t<flags>\t<exceptions>\t<status>\t<source>

A unit covers the functions whose start address satisfies `lo <= va < hi` (`hi` is the
end of its last function); units never overlap and never cross a function. `flags` is
the complete flag string except the exception mode, which is the `exceptions` column
(`on`/`off`) and becomes `-Cpp_exceptions off` on the command line of an MWCC compile
when it is off (nothing is passed for `on`, the compiler default, and nothing for the
Sony EE GCC, which has no such switch). `status` is `-` or `provisional`: a provisional
unit is one whose members' evidence has no common profile, so the row carries the
majority profile and the dissenting members keep per-function overrides.

Per-function rows in config/SLUS-20836/unit-flags.tsv and config/SLUS-20836/unit-compilers.tsv are
**overrides** of the unit profile. Where a unit covers the function they are allowed
only when marked `provisional` (tools/unitflags.py, tools/unitcompilers.py); an
override is applied by the verifier only after the unit profile failed to reproduce
the code bytes, and a function that matches only that way is reported in the
`foreign-profile` category (tools/check.py), which is debt, never a match. A table
without a unit for the address (a test fixture) falls back to the
caller's defaults plus the plain overrides, as before this table existed.
"""
import bisect
import os
import re
from collections import namedtuple
from functools import lru_cache
from pathlib import Path

import cc
import unitcompilers
import unitflags

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_PATH = "config/SLUS-20836/units.tsv"
SYMBOLS_DEFAULT = os.path.join(ROOT, "config", "SLUS-20836", "symbols.txt")
STATUSES = ("-", "provisional")
EXCEPTION_MODES = ("on", "off")

Unit = namedtuple("Unit", "lo hi name compiler flags exceptions status source")
Profile = namedtuple("Profile", "compiler flags exceptions")
Resolution = namedtuple("Resolution", "unit profile override redundant")
Table = namedtuple("Table", "path compilers units starts")


def _resolve(path):
    return path if os.path.isabs(path) else os.path.join(ROOT, path)


def units_path(symbols=None, explicit=None):
    """The units table that belongs to a symbol map, or None when there is none.

    The repository's map uses config/SLUS-20836/units.tsv; any other map (a test
    fixture's) uses the `units.tsv` beside it, which may not exist — then no
    unit profile is known and the callers' defaults apply.
    """
    if explicit is not None:
        return _resolve(explicit)
    if symbols is None or os.path.realpath(symbols) == os.path.realpath(SYMBOLS_DEFAULT):
        return _resolve(DEFAULT_PATH)
    beside = os.path.join(os.path.dirname(os.path.abspath(symbols)), "units.tsv")
    return beside if os.path.exists(beside) else None


def parse(text, path="units.tsv"):
    """Parse a units table -> Table. Raises ValueError on a malformed row."""
    compilers, units = {}, []
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        fields = line.rstrip("\n").split("\t")
        where = f"{os.path.basename(path)}:{number}"
        if fields[0] == "@compiler":
            if len(fields) != 4:
                raise ValueError(f"{where}: @compiler takes id, executable and SHA-256")
            _, ident, executable, digest = fields
            relative = Path(executable)
            if relative.is_absolute() or ".." in relative.parts:
                raise ValueError(f"{where}: executable must be repository-relative")
            if len(digest) != 64 or any(c not in "0123456789abcdef" for c in digest):
                raise ValueError(f"{where}: expected lowercase SHA-256")
            if ident in compilers:
                raise ValueError(f"{where}: duplicate compiler id {ident!r}")
            compilers[ident] = (executable, digest)
            continue
        if len(fields) < 7:
            raise ValueError(f"{where}: expected lo, hi, name, compiler, flags, exceptions, status[, source]")
        lo_s, hi_s, name, compiler, flags, exceptions, status = fields[:7]
        source = fields[7] if len(fields) > 7 else ""
        try:
            lo, hi = int(lo_s, 16), int(hi_s, 16)
        except ValueError:
            raise ValueError(f"{where}: addresses must be hexadecimal") from None
        if not lo < hi:
            raise ValueError(f"{where}: empty or inverted range")
        if compiler not in compilers:
            raise ValueError(f"{where}: unknown compiler id {compiler!r} (declare it with @compiler first)")
        if exceptions not in EXCEPTION_MODES:
            raise ValueError(f"{where}: exceptions must be on or off")
        if status not in STATUSES:
            raise ValueError(f"{where}: status must be - or provisional")
        units.append(Unit(lo, hi, name, compiler, flags.strip(), exceptions, status, source))
    units.sort()
    for a, b in zip(units, units[1:]):
        if b.lo < a.hi:
            raise ValueError(f"{os.path.basename(path)}: units {a.name} and {b.name} overlap")
    return Table(path, compilers, units, [u.lo for u in units])


@lru_cache(maxsize=8)
def load(path=DEFAULT_PATH):
    """Load a units table (cached by path). A missing file is an empty table."""
    full = _resolve(path)
    if not os.path.exists(full):
        return Table(full, {}, [], [])
    with open(full) as fh:
        return parse(fh.read(), full)


def unit_for(va, table):
    """The Unit covering `va`, or None."""
    if table is None or not table.units:
        return None
    i = bisect.bisect_right(table.starts, va) - 1
    if i >= 0 and table.units[i].lo <= va < table.units[i].hi:
        return table.units[i]
    return None


# A listed compiler must exist and match its digest; falling back to another build would
# hide a profile error behind a mismatch, so both failures raise ValueError.
checked_executable = unitcompilers.checked_executable


def split_exceptions(flags):
    """-> (flags without the exception switch, "on"/"off"/None as the switch said)."""
    tokens = flags.split()
    mode = None
    while "-Cpp_exceptions" in tokens:
        i = tokens.index("-Cpp_exceptions")
        if i + 1 < len(tokens) and tokens[i + 1] in EXCEPTION_MODES:
            mode = tokens[i + 1]
            del tokens[i:i + 2]
        else:
            del tokens[i]
    return " ".join(tokens), mode


def command_flags(profile):
    """The flag string a compile of this profile is run with."""
    if profile.exceptions == "off" and not cc.is_eegcc(profile.compiler):
        return (profile.flags + " -Cpp_exceptions off").strip()
    return profile.flags


# An asm body (docs/engine/asm-body-matches.md) is the retail instructions wrapped in an MWCC
# `asm` function under `#pragma optimization_level 0`: not compiled code, so no profile shapes
# its bytes, and only MWCC parses it. It links from `src/` but recovers nothing, so `make check`
# files it under its own category and no matched figure counts it.
ASM_PRAGMA = "#pragma optimization_level 0"
ASM_DEF_RE = re.compile(r"^\s*asm\s+[^;{()]*?\b(\w+)\s*\(", re.M)
_ASM_CACHE = {}


def asm_body_names(path):
    """The functions `path` defines as asm bodies (decided by content, never by folder): an
    `asm <type> name(` definition, with or without the pragma. A C function with an inline
    `asm { sync }` statement is not an asm body."""
    try:
        stamp = os.stat(path).st_mtime_ns
    except OSError:
        return frozenset()
    hit = _ASM_CACHE.get(path)
    if hit is None or hit[0] != stamp:
        try:
            text = open(path, errors="replace").read()
        except OSError:
            return frozenset()
        names = frozenset(ASM_DEF_RE.findall(text)) if "asm" in text else frozenset()
        hit = (stamp, names)
        _ASM_CACHE[path] = hit
    return hit[1]


def asm_body_source(path):
    """True when `path` defines asm bodies."""
    return bool(asm_body_names(path))


def for_source(profile, source, default_flags, default_compiler, root=ROOT):
    """The profile a compile of `source` runs with: the unit's, except that an asm body in a
    Sony EE GCC unit is built by the default MWCC with the default flags (GCC cannot parse it and
    no flag shapes its bytes). Everything else is returned unchanged."""
    if cc.is_eegcc(profile.compiler) and asm_body_source(source):
        compiler = default_compiler if os.path.isabs(default_compiler) else os.path.join(root, default_compiler)
        flags, mode = split_exceptions(default_flags)
        return Profile(compiler, flags, mode or "on")
    return profile


def same_profile(left, right):
    return (os.path.realpath(left.compiler) == os.path.realpath(right.compiler)
            and left.flags.split() == right.flags.split()
            and left.exceptions == right.exceptions)


def resolve(va, default_flags, default_compiler, units=None, unit_flags=None, unit_compilers=None,
            symbols=None, root=ROOT):
    """The profiles that apply to the function at `va` -> Resolution.

    `profile` is the unit's. Outside every unit it is the caller's defaults (with the
    exception mode the defaults imply: `-Cpp_exceptions` in `default_flags`, else on),
    replaced by the per-function rows where they exist: there the rows are the whole
    profile, as they were before units.tsv. Inside a unit `override` is the row profile
    when it differs from the unit's, else None, and `redundant` is True when rows exist
    but repeat the unit profile. Raises ValueError for a missing or changed compiler,
    and for a per-function row inside a unit that is not marked provisional.
    """
    table = load(units) if units is not None else load(units_path(symbols) or "/nonexistent/units.tsv")
    unit = unit_for(va, table)
    if unit is not None:
        executable, digest = table.compilers[unit.compiler]
        compiler = checked_executable(executable, digest, root)
        profile = Profile(compiler, unit.flags, unit.exceptions)
    else:
        flags, mode = split_exceptions(default_flags)
        compiler = default_compiler if os.path.isabs(default_compiler) else os.path.join(root, default_compiler)
        profile = Profile(compiler, flags, mode or "on")
    flag_rows = unitflags.load_rows(unit_flags or unitflags.DEFAULT_PATH)
    compiler_rows = unitcompilers.load_rows(unit_compilers or unitcompilers.DEFAULT_PATH)
    flag_row, compiler_row = flag_rows.get(va), compiler_rows.get(va)
    if flag_row is None and compiler_row is None:
        return Resolution(unit, profile, None, False)
    o_compiler = profile.compiler
    if compiler_row is not None:
        o_compiler = checked_executable(compiler_row.executable, compiler_row.digest, root)
    o_flags, o_mode = profile.flags, profile.exceptions
    if flag_row is not None:
        o_flags, mode = split_exceptions(flag_row.flags)
        if mode is not None:
            o_mode = mode
    rows = Profile(o_compiler, o_flags, o_mode)
    if unit is None:
        # outside every unit the rows are the whole profile, as before units.tsv existed
        return Resolution(None, rows, None, False)
    for row, table_name in ((flag_row, "unit-flags.tsv"), (compiler_row, "unit-compilers.tsv")):
        if row is not None and row.status != "provisional":
            raise ValueError(f"per-function row for 0x{va:x} in {table_name} is not marked provisional; "
                             f"the unit profile of {unit.name} covers it (config/SLUS-20836/units.tsv)")
    if same_profile(rows, profile):
        return Resolution(unit, profile, None, True)
    return Resolution(unit, profile, rows, False)


def profile_key(va, default_flags, default_compiler, units=None, unit_flags=None, unit_compilers=None,
                symbols=None, root=ROOT):
    """A string that changes whenever the profile resolution for `va` would (for cache keys).

    Covers the unit row, the compiler table entries it names (path and content digest),
    and the per-function rows; a resolution error is part of the key too.
    """
    table = load(units) if units is not None else load(units_path(symbols) or "/nonexistent/units.tsv")
    unit = unit_for(va, table)
    parts = ["unit %r" % (unit,)]
    if unit is not None:
        executable, digest = table.compilers[unit.compiler]
        parts.append("compiler %s %s %s" % (unit.compiler, executable, digest))
    parts.append("flags-row %r" % (unitflags.load_rows(unit_flags or unitflags.DEFAULT_PATH).get(va),))
    parts.append("compiler-row %r" % (unitcompilers.load_rows(unit_compilers or unitcompilers.DEFAULT_PATH).get(va),))
    try:
        res = resolve(va, default_flags, default_compiler, units, unit_flags, unit_compilers, symbols, root)
        parts.append("resolved %r %r %r" % (res.profile, res.override, res.redundant))
    except ValueError as error:
        parts.append("error %s" % error)
    return "\n".join(parts)

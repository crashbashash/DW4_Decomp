#!/usr/bin/env python3
"""compiler_names.py — the compiler-name map, config/SLUS-20836/compiler-names.tsv.

A C++ definition reaches the object under its compiler (mangled) name, `setVisualContext__10igRendererFP15igVisualContext`,
while symbols.txt keeps the retail key, `igRenderer_SetVisualContext`. The unit that defines a member binds the two in its
unit-objects.json row: the `emitted` key (or the owner's `symbol`) at the member's retail address, a `duplicates` key for an
inline copy it compiles, a `data` key for a static data member or vtable it places. `make check` proves each of those
bindings against the compile of the source. This map gathers them into one table:

    <compiler name> <retail address> <retail name>

the retail name being the symbols.txt key of a function, else the data-names.tsv name of a datum (`DAT_<address>` when it
has none). Every other unit then reaches the member through the map (`verify.sym_address`, the link's renames), with no
`externals` row of its own; an inline copy a unit compiles is still a `duplicates` row, since its bytes are compared.

A name enters the map when `tools/demangle.py` reads it as a compiler name, symbols.txt does not already hold it, and every
row binding it (any of `symbol`, `emitted`, `duplicates`, `externals`, `data`) gives the same address: a name two units bind
to different functions (a file-local helper class's destructor) stays a per-unit binding.

    python3 tools/compiler_names.py            # print the table
    python3 tools/compiler_names.py --write    # write it
    python3 tools/compiler_names.py --check    # fail when the written table differs from the rows (make hygiene)
"""
import argparse
import collections
import os
import sys
from functools import lru_cache

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import unitobjects  # noqa: E402
from demangle import demangle  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_SYMBOLS = "config/SLUS-20836/symbols.txt"
HEADER = ("# compiler name<TAB>retail address<TAB>retail name. GENERATED by tools/compiler_names.py --write from the\n"
          "# unit-objects.json rows; never edited by hand (docs/engine/emitted-functions.md#the-compiler-name-map).\n")


def table_path(symbols=DEFAULT_SYMBOLS):
    """The map beside `symbols`."""
    base = symbols if os.path.isabs(symbols) else os.path.join(ROOT, symbols)
    return os.path.join(os.path.dirname(base), "compiler-names.tsv")


def _parse(text, path):
    out = {}
    for number, line in enumerate(text.splitlines(), 1):
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != 3:
            raise ValueError(f"{path}:{number}: expected compiler name, address and retail name")
        name, address, retail = fields
        if name in out:
            raise ValueError(f"{path}:{number}: {name} listed twice")
        out[name] = (int(address, 16), retail)
    return out


@lru_cache(maxsize=8)
def _load(path, mtime_ns, size):
    with open(path) as fh:
        return _parse(fh.read(), path)


def load(symbols=DEFAULT_SYMBOLS):
    """{compiler name: (retail address, retail name)} from the map beside `symbols`; empty when there is none."""
    path = table_path(symbols)
    try:
        st = os.stat(path)
    except OSError:
        return {}
    return _load(path, st.st_mtime_ns, st.st_size)


def build(groups, by_va, data_names):
    """[(compiler name, address, retail name)] in address order, from unit-objects `groups`, symbols.txt's
    {va: (name, size)} and data-names.tsv's {name: va}."""
    by_name = {name for name, _size in by_va.values()}
    data_at = {}
    for name, va in sorted(data_names.items()):
        data_at.setdefault(va, name)
    bound = collections.defaultdict(set)
    for group in groups:
        pairs = list(group.emitted) + list(group.duplicates) + list(group.externals) + list(group.data)
        if group.symbol:
            pairs.append((group.symbol, group.owner))
        for name, address in pairs:
            bound[name].add(address)
    rows = []
    for name, addresses in bound.items():
        if len(addresses) != 1 or name in by_name or demangle(name) is None:
            continue
        address = next(iter(addresses))
        retail = by_va[address][0] if address in by_va else data_at.get(address, "DAT_%08x" % address)
        rows.append((name, address, retail))
    return sorted(rows, key=lambda row: (row[1], row[0]))


def render(rows):
    return HEADER + "".join("%s\t0x%08x\t%s\n" % row for row in rows)


def generate(symbols=DEFAULT_SYMBOLS, unit_objects=None):
    import verify
    _by_name, by_va = verify.load_symbols(symbols)
    return render(build(unitobjects.load(unit_objects), by_va, verify.data_symbols(symbols)))


def write(symbols=DEFAULT_SYMBOLS, unit_objects=None):
    """Write the map beside `symbols` from the rows; (its path, the number of names)."""
    text = generate(symbols, unit_objects)
    path = table_path(symbols)
    with open(path, "w") as fh:
        fh.write(text)
    return path, text.count("\n") - HEADER.count("\n")


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--symbols", default=DEFAULT_SYMBOLS)
    ap.add_argument("--unit-objects", default=None)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="write the table beside symbols.txt")
    mode.add_argument("--check", action="store_true", help="fail when the written table is stale")
    a = ap.parse_args(argv)
    if a.write:
        path, count = write(a.symbols, a.unit_objects)
        print("compiler_names: %d names -> %s" % (count, os.path.relpath(path, ROOT)))
        return 0
    text = generate(a.symbols, a.unit_objects)
    path = table_path(a.symbols)
    if a.check:
        try:
            with open(path) as fh:
                written = fh.read()
        except OSError:
            written = None
        if written != text:
            print("compiler_names: %s is stale; run python3 tools/compiler_names.py --write"
                  % os.path.relpath(path, ROOT), file=sys.stderr)
            return 1
        print("compiler_names: %s matches the rows" % os.path.relpath(path, ROOT))
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())

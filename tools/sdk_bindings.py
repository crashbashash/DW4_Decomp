#!/usr/bin/env python3
"""Decode the SDK's library descriptors in game.elf's rodata.

Eight records sit in the `0x481000+` window, each opening with a **12-byte
space-padded library name and a 4-byte ASCII version** -- `PsIIlibgraph2800`,
`PsIIlibdma  2800`, ... `PsIIlibmc   2810`. The version is real and per-library
(`2800` = SDK 2.8.0, `mc` is `2810`), which is also the string in the disc's
`IOPRP280.IMG`. Nothing references these records (no data word, no `lui`+`addiu`,
not gp-relative), so they are linker-emitted metadata rather than runtime tables:
the game never reads them.

What the payload is depends on the library, and that is the point of this tool:

  * `dma`   -- ten EE DMA channel register bases (`0x10008000`..`0x1000d400`)
               followed by **16 code pointers**: a real function table.
  * `graph` -- u16 pair tables (no code pointers).
  * `ipu`   -- the MPEG-2 DCT quantisation tables (an intra zig-zag matrix and
               the all-16 non-intra default) plus microcode.
  * `kernl` -- the C heap base `0x0058D280` (the same value the CRT passes to
               syscall 61), one code pointer, and a long run of
               `0xffffffff` marking absent entries.
  * `pad`   -- ten pointers into the shared string pool: the status names
               ERROR / STABLE / EXECCMD / FINDCTP1 / DISCONNECT / BUSY / FAILED
               / COMPLETE.
  * `mc`    -- driver structures on an 88-byte stride and a 20-entry pointer
               table; `cdvd` and `sdr` carry no code pointers at all.

So the descriptors give a `function -> library` map for **libdma only**; for the
other seven they identify the library's *data*, not its functions. That is a
stated limit, not a missing decoder: per-library extents cannot be had this way
(see docs/engine/platform-boundary.md). The two consequences worth keeping:

  1. libdma's table names 16 functions at `0x104478`..`0x105050`, of which 13
     are known function starts and **3 are boundaries the symbol table missed**
     (`0x104478` and `0x1044f0` inside `FUN_00104258`, `0x105050` unclaimed) --
     each ends exactly where the next begins, so the table is a split oracle.
  2. The same window holds the VU1 microcode's own symbol table and the
     renderer's technique table, which are recorded separately; this tool only walks the eight descriptors.

A record's `span` is bounded by the *next descriptor*, not by the record's own
length, so a long span picks up unrelated rodata: `kernl`'s 5,888-byte span and
`cdvd`'s 7,096-byte span contain other libraries' data, and only the dense
pointer runs and the string tables are evidence of the library's own. libdma's
function table is the one that matters, and it is bounded by its own shape.

Usage:
    tools/sdk_bindings.py [--elf orig/SLUS-20836/SLUS_208.36] [--symbols config/SLUS-20836/symbols.txt]
                          [--json data/sdk-bindings.json]
"""
import argparse
import json
import re
import struct
import sys

VADDR, FILE_BASE = 0x100000, 0x80
# The window the descriptors live in; nothing SDK-ish is above it
# except the EE runtime, which has no descriptors.
SCAN_LO, SCAN_HI = 0x481000, 0x4d2000
# EE register blocks: a word here is a hardware base, not a pointer.
MMIO_LO, MMIO_HI = 0x10000000, 0x10010000
CODE_LO, CODE_HI = 0x100000, 0x554b00
HEADER = re.compile(rb'[A-Za-z][A-Za-z0-9_.\-]{2,11}')


def load(path):
    with open(path, "rb") as fh:
        return fh.read()


def load_symbols(path):
    """`va size name` per line, as config/SLUS-20836/symbols.txt is generated by split.py."""
    syms = []
    with open(path) as fh:
        for ln in fh:
            if ln.startswith("#"):
                continue
            p = ln.split()
            if len(p) >= 3:
                syms.append((int(p[0], 16), int(p[1], 16), p[2]))
    syms.sort()
    return syms


class Image:
    def __init__(self, blob, syms):
        self.blob = blob
        self.syms = syms
        self.starts = [s[0] for s in syms]
        # Every address a function ends at. An unclaimed pointer there is not
        # random data: it is a function start the tiling missed, because the
        # functions are contiguous.
        self.ends = {a + sz for a, sz, _ in syms}

    def w32(self, va):
        off = va - VADDR + FILE_BASE
        if off < 0 or off + 4 > len(self.blob):
            return None
        return struct.unpack_from("<I", self.blob, off)[0]

    def in_image(self, va):
        return VADDR <= va < 0x58D280

    def code(self, va):
        return CODE_LO <= va < CODE_HI and va % 4 == 0

    def covering(self, va):
        """The symbol containing `va`, as (start, name, size)."""
        import bisect

        i = bisect.bisect_right(self.starts, va) - 1
        if i < 0:
            return None
        a, sz, nm = self.syms[i]
        if a <= va < a + sz:
            return (a, nm, sz)
        return None

    def at(self, va):
        return self.covering(va)

    def string_at(self, va):
        """The printable run starting at `va`, if any -- rodata pointers point at
        strings, which is how libpad's status table is identified."""
        off = va - VADDR + FILE_BASE
        if off < 0 or off >= len(self.blob):
            return None
        end = off
        while end < len(self.blob) and 0x20 <= self.blob[end] < 0x7F:
            end += 1
        s = self.blob[off:end]
        return s.decode() if len(s) >= 4 else None


# EE register blocks the descriptors carry, named so the JSON is readable.
MMIO_NAMES = {
    0x10008000: "D0_CHCR/VIF0", 0x10009000: "D1_CHCR/VIF1", 0x1000A000: "D2_CHCR/GIF",
    0x1000B000: "D3_CHCR/fromIPU", 0x1000B400: "D4_CHCR/toIPU", 0x1000C000: "D5_CHCR/SIF0",
    0x1000C400: "D6_CHCR/SIF1", 0x1000C800: "D7_CHCR/SIF2", 0x1000D000: "D8_CHCR/SPR0",
    0x1000D400: "D9_CHCR/SPR1",
}


def mmio_name(w):
    return MMIO_NAMES.get(w, "mmio")


def find_descriptors(img):
    """Every 16-byte `name` + 4-digit-version header in the window."""
    out = []
    lo = SCAN_LO - VADDR + FILE_BASE
    hi = min(SCAN_HI - VADDR + FILE_BASE, len(img.blob))
    seg = img.blob[lo:hi]
    for m in HEADER.finditer(seg):
        name = m.group()
        s, e = m.start(), m.end()
        tail = seg[e:e + 16 - len(name)]
        pad, ver = tail[:12 - len(name)], tail[12 - len(name):16 - len(name)]
        if not all(c in (0x20, 0x00) for c in pad):
            continue
        if not re.fullmatch(rb"[0-9]{4}", ver):
            continue
        va = SCAN_LO + s
        # A real descriptor has its name at a 4-byte boundary.
        if va % 4:
            continue
        out.append({"va": va, "name": name.decode(), "version": ver.decode()})
    return out


def decode(img, desc, next_va):
    """Classify the words between a descriptor's header and the next one.

    A word matters here only if it is *covered by a function*: the functions tile
    the code region, so an address inside a function is code, while an address in
    an unclaimed gap is rodata or data. That distinction is what separates
    libdma's function table from libpad's string table -- both are runs of words
    that look identical until you ask whether anything covers them.

    The function table is then the longest aligned run with no gap: ld/libdma's
    fourteen words of register bases stop exactly where its sixteen function
    pointers begin, so a dense run is unmistakable.
    """
    start = desc["va"] + 16
    end = next_va if next_va else min(desc["va"] + 0x400, SCAN_HI)
    rec = {
        "va": desc["va"], "name": desc["name"], "version": desc["version"],
        "span": end - desc["va"], "mmio_bases": [], "code_entries": [],
        "data_ptrs": [], "run": None,
    }
    code = []
    va = start
    while va + 4 <= end:
        w = img.w32(va)
        if w is None:
            break
        if MMIO_LO <= w < MMIO_HI:
            rec["mmio_bases"].append({"va": va, "value": w, "name": mmio_name(w)})
        elif img.covering(w):
            code.append({"va": va, "value": w})
        elif img.in_image(w):
            item = {"va": va, "value": w}
            s = img.string_at(w)
            if s:
                item["string"] = s
            if w in img.ends:
                # Nothing covers it, but it begins exactly where a function ends
                # and a descriptor table holds it: that is a code entry the
                # tiling missed, not data.
                item["at_function_end"] = True
                item["entry_point"] = False
                rec.setdefault("_late_code", []).append(item)
                va += 4
                continue
            rec["data_ptrs"].append(item)
        va += 4
    run = []
    for item in code:
        if run and item["va"] != run[-1]["va"] + 4:
            run = []
        run.append(item)
        if rec["run"] is None or len(run) > len(rec["run"]):
            rec["run"] = list(run)
    for item in rec.get("run") or []:
        c = img.covering(item["value"])
        item["symbol"] = c[1] if c else None
        item["entry_point"] = bool(c and c[0] == item["value"])
    # an address the tiling missed entirely belongs in the table too -- the run is
    # bounded by what the tiling knows, so it cannot include it
    late = rec.pop("_late_code", [])
    if rec.get("run") and len(rec["run"]) >= 3:
        rec["code_entries"] = sorted(rec["run"] + late, key=lambda e: e["va"])
    else:
        rec["code_entries"] = sorted(late, key=lambda e: e["va"])
    if not rec["code_entries"]:
        rec["run"] = None
    return rec


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--elf", default="orig/SLUS-20836/SLUS_208.36")
    ap.add_argument("--symbols", default="config/SLUS-20836/symbols.txt")
    ap.add_argument("--json")
    args = ap.parse_args()

    img = Image(load(args.elf), load_symbols(args.symbols))
    descs = find_descriptors(img)
    recs = []
    for i, d in enumerate(descs):
        nxt = descs[i + 1]["va"] if i + 1 < len(descs) else None
        recs.append(decode(img, d, nxt))

    print("SDK library descriptors: %d" % len(recs))
    for r in recs:
        print("  0x%06x  %-13s %s  span %5d  reg bases %2d  data ptrs %2d  "
              "function table %s"
              % (r["va"], r["name"], r["version"], r["span"],
                 len(r["mmio_bases"]), len(r["data_ptrs"]),
                 "%d entries" % len(r["code_entries"]) if r["code_entries"] else "none"))
    print("\n  which library gives a function table:")
    for r in recs:
        if r["code_entries"]:
            n = sum(1 for e in r["code_entries"] if e.get("entry_point"))
            print("     %-8s %d entries, %d are known function starts"
                  % (r["name"], len(r["code_entries"]), n))
    missing = [(r["name"], e["value"], "inside " + (e.get("symbol") or "?"))
               for r in recs for e in r["code_entries"] if not e.get("entry_point")]
    missing += [(r["name"], d["value"], "unclaimed, but exactly a function end")
                for r in recs for d in r["data_ptrs"] if d.get("at_function_end")]
    if missing:
        print("\n  split oracle -- pointers that are function starts the tiling missed:")
        for lib, va, why in missing:
            print("     %-8s 0x%06x  %s" % (lib, va, why))

    if args.json:
        with open(args.json, "w") as fh:
            json.dump({"descriptors": recs}, fh, indent=1)
            fh.write("\n")
        print("\nwrote %s" % args.json)
    return 0


if __name__ == "__main__":
    sys.exit(main())

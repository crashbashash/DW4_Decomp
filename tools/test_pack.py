import os
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools"))
import pack  # noqa: E402
import units  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPT = os.path.join(ROOT, "tools", "pack.py")


class PackTest(unittest.TestCase):
    def run_pack(self, function, *extra, ext=".c"):
        with tempfile.TemporaryDirectory() as out:
            r = subprocess.run([sys.executable, SCRIPT, "--function", function, "--out", out, *extra],
                               cwd=ROOT, capture_output=True, text=True)
            self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
            with open(os.path.join(out, "pack.md")) as fh:
                md = fh.read()
            with open(os.path.join(out, "pack" + ext)) as fh:
                return md, fh.read()

    def test_a_member_is_found_by_its_cxx_name(self):
        # Gap::Lua::igLuaState::runString is the definition of igLuaState_RunString
        for name in ("igLuaState::runString", "runString__Q33Gap3Lua10igLuaStateFPCc"):
            md, cpp = self.run_pack(name, "--keep", "0", ext=".cpp")
            self.assertIn("- function: `igLuaState_RunString` at 0x00246620", md)
            self.assertIn("int igLuaState::runString(const char *source) {\n", cpp)
            self.assertIn("kept `runString`", md)

    def test_a_definition_maps_to_the_member_its_class_and_name_spell(self):
        pack.load_tools(ROOT)
        text = "int A::get() {\n return 1;\n}\nint B::get() {\n return 2;\n}\n"
        group = type("Group", (), {"emitted": (("get__1BFv", 0x200), ("get__1AFv", 0x100)), "owner": 0x300,
                                   "symbol": ""})()
        defs = pack.map_definitions(text, text, units.definitions(text), [], None, group)
        self.assertEqual([va for _n, _s, _e, va in defs], [0x100, 0x200])

    def test_target_kept_others_elided(self):
        # src/cri/sjcrs.c holds seven small matched functions in one unit
        md, c = self.run_pack("SJCRS_Lock", "--keep", "0")
        self.assertIn("{\n    SVM_Lock();\n}", c)
        self.assertNotIn("SVM_Unlock();\n}", c)
        self.assertEqual(c.count("body elided"), 6)
        self.assertIn("{ /* body elided: 20 B, MATCH */ }", c)
        self.assertIn("- function: `SJCRS_Lock` at 0x0027b2b0, 20 B", md)
        self.assertIn("- source: `src/cri/sjcrs.c`", md)

    def test_neighbours_kept(self):
        _md, c = self.run_pack("SJCRS_Lock", "--keep", "1")
        self.assertIn("SVM_Unlock();\n}", c)
        self.assertEqual(c.count("body elided"), 4)

    def test_notes_and_near_misses_optional(self):
        with tempfile.TemporaryDirectory() as notes:
            with open(os.path.join(notes, "SJCRS_Lock.md"), "w") as fh:
                fh.write("note\n")
            tsv = os.path.join(notes, "nm.tsv")
            with open(tsv, "w") as fh:
                fh.write("id\tname\taddr\tdiff\nr1\tSJCRS_Lock\t0x0027b2b0\t2\n")
            md, _c = self.run_pack("SJCRS_Lock", "--notes-dir", notes, "--near-misses", tsv)
            self.assertIn("SJCRS_Lock.md", md)
            self.assertIn("  - diff: 2", md)
        md, _c = self.run_pack("SJCRS_Lock")
        self.assertNotIn("note file", md)
        self.assertNotIn("near-miss", md)


ASM = """/* Foo — 0x00100000, 24 bytes. GENERATED by tools/split.py; do not edit. */
	.section .text
Foo:
	.word 0x0c000000  /* 00100000: jal\t0x100100 */
	.word 0x0c000000  /* 00100004: jal\t0x100200 */
	.word 0x08000000  /* 00100008: j\t0x100010 */
	.word 0x08000000  /* 0010000c: j\t0x100300 */
"""
SYMS = [(0x100000, 0x20, "Foo", ""), (0x100100, 8, "Declared", ""), (0x100200, 8, "Bare", "FUN_00100200"),
        (0x100300, 8, "TailCallee", "")]


class PackSectionsTest(unittest.TestCase):
    def sections(self, repo, declared, body, ref_dirs=()):
        lines = []
        pack.units = units
        pack.tail_sections(lines.append, repo, "Foo", "", 0x100000, 0x20, {r[0]: r for r in SYMS}, SYMS,
                           declared, body, list(ref_dirs))
        return "\n".join(lines)

    def test_asm_absent_is_a_note(self):
        with tempfile.TemporaryDirectory() as repo:
            md = self.sections(repo, {"Declared"}, "")
            self.assertIn("## Retail assembly\n\nnone: `asm/` is absent", md)

    def test_asm_lines_and_callees(self):
        with tempfile.TemporaryDirectory() as repo:
            os.mkdir(os.path.join(repo, "asm"))
            with open(os.path.join(repo, "asm", "Foo.s"), "w") as fh:
                fh.write(ASM)
            md = self.sections(repo, {"Declared"}, "")
            self.assertIn("From `asm/Foo.s`.", md)
            self.assertIn("/* 0010000c: j\t0x100300 */", md)
            tail = md.split("## Callees without a prototype")[1]
            self.assertNotIn("`Declared`", tail)
            self.assertIn("- `Bare` (`FUN_00100200`) at 0x00100200 (retail jal/j)", tail)
            self.assertIn("- `TailCallee` at 0x00100300", tail)       # a tail call out of the function
            self.assertNotIn("0x00100010", tail)                      # a `j` inside the function is not a call
            # an alias declaration counts as a prototype
            self.assertNotIn("`Bare`", self.sections(repo, {"FUN_00100200", "TailCallee"}, ""))

    def test_asm_found_by_address(self):
        with tempfile.TemporaryDirectory() as repo:
            os.mkdir(os.path.join(repo, "asm"))
            with open(os.path.join(repo, "asm", "Other.s"), "w") as fh:
                fh.write(ASM)
            self.assertEqual(pack.find_asm(repo, "Foo", 0x100000), os.path.join(repo, "asm", "Other.s"))
            self.assertIsNone(pack.find_asm(repo, "Foo", 0x100004))

    def test_c_body_calls_without_asm(self):
        with tempfile.TemporaryDirectory() as repo:
            md = self.sections(repo, set(), "void Foo(void) { Bare(1); local(2); if (x) {} }")
            tail = md.split("## Callees without a prototype")[1]
            self.assertIn("- `Bare` (`FUN_00100200`) at 0x00100200 (C body)", tail)
            self.assertNotIn("local", tail)                           # not a symbol of the program
            self.assertIn("not checked", self.sections(repo, None, None))

    def test_ref_dirs(self):
        with tempfile.TemporaryDirectory() as repo, tempfile.TemporaryDirectory() as refs:
            os.mkdir(os.path.join(refs, "sub"))
            with open(os.path.join(refs, "sub", "b.c"), "w") as fh:
                fh.write("x\nFoo(1);\nFooBar();\nFUN_00100000\n")
            with open(os.path.join(refs, "a.txt"), "w") as fh:
                fh.write("nothing here\n")
            with open(os.path.join(refs, "bin.dat"), "wb") as fh:
                fh.write(b"Foo\0")
            md = self.sections(repo, set(), "", [refs])
            self.assertIn("## Reference sources", md)
            self.assertIn("- `%s`: lines 2, 4" % os.path.join(refs, "sub", "b.c"), md)
            self.assertNotIn("a.txt", md)
            self.assertNotIn("bin.dat", md)
            self.assertEqual(md, self.sections(repo, set(), "", [refs]))
            self.assertNotIn("Reference sources", self.sections(repo, set(), ""))


if __name__ == "__main__":
    unittest.main()
